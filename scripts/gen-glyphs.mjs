// Builds src/components/needt3/glyphs/glyph-data.ts from the landing glyph
// SVGs in ./svg. Hex hues become design-system tokens so a glyph follows the
// theme (the landing hard-codes light-theme colours).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(
  dirname(fileURLToPath(import.meta.url)),
  "../src/components/needt3/glyphs"
);
const mix = (c, a) =>
  a >= 0.995
    ? c
    : `color-mix(in oklch, ${c} ${Math.round(a * 100)}%, transparent)`;
const VIOLET = "oklch(0.62 0.19 300)";
const AMBER = "#ed990e";

function hueOf(r, g, b) {
  if (Math.max(r, g, b) - Math.min(r, g, b) < 24) return "var(--text-primary)";
  if (r > 140 && b > 190 && g < 130 && r - g > 40 && b > r) return VIOLET;
  if (b > r && b > g) return "var(--accent)";
  if (g > r && g > b) return "var(--success)";
  if (r > 200 && g < 60) return "var(--destructive)";
  return AMBER;
}
function swap(s) {
  s = s.replace(
    /rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/g,
    (_, r, g, b, a) => mix(hueOf(+r, +g, +b), +a)
  );
  const hex = {
    "#ffffff": "var(--surface-raised)",
    "#5a5ce2": "var(--accent)",
    "#098926": "var(--success)",
    "#e6000c": "var(--destructive)",
    "#9964e5": VIOLET,
    "#ed990e": AMBER,
    "#1a1c1e": "var(--text-primary)",
  };
  return s.replace(/#[0-9a-fA-F]{6}\b/g, (h) => hex[h.toLowerCase()] ?? h);
}
const out = {};
for (const f of readdirSync(join(dir, "svg")).sort()) {
  const src = readFileSync(join(dir, "svg", f), "utf8").trim();
  const m = src.match(/^<svg[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/);
  if (!m) throw new Error(f);
  out[f.replace(".svg", "")] = {
    vb: m[1],
    body: swap(m[2]).replace(/\s*\/>/g, "/>"),
  };
}
const names = Object.keys(out);
writeFileSync(
  join(dir, "glyph-data.ts"),
  `/* GENERATED by scripts/gen-glyphs.mjs from ./svg (the landing glyphs). Do not edit. */\n` +
    `export const GLYPH_NAMES = ${JSON.stringify(names)} as const;\n` +
    `export type GlyphName = (typeof GLYPH_NAMES)[number];\n` +
    `export const GLYPHS: Record<GlyphName, { vb: string; body: string }> = ${JSON.stringify(out, null, 2)};\n`
);
